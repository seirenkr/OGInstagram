test("edge cache key separates every public hostname", () => {
  const hosts = ["oginstagram.com", "www.oginstagram.com", "d.oginstagram.com", "g.oginstagram.com"];
  const keysBySite = new Map();
  for (const host of hosts) {
    const url = new URL(`https://${host}/p/Ab_12/`);
    const route = resolveContainerRoute(url);
    assert.notEqual(route, null, host);
    const key = edgeCacheKey(route, url);
    keysBySite.set(key, host);
  }
  assert.equal(keysBySite.size, 4);
  const plain = resolveContainerRoute(new URL("https://oginstagram.com/p/Ab_12/"));
  const www = resolveContainerRoute(new URL("https://www.oginstagram.com/p/Ab_12/"));
  assert.notEqual(
    edgeCacheKey(plain, new URL("https://oginstagram.com/p/Ab_12/")),
    edgeCacheKey(www, new URL("https://www.oginstagram.com/p/Ab_12/"))
  );
});

test("public __gallery input is stripped and cannot change a plain-host response", () => {
  const plain = new URL("https://oginstagram.com/p/Ab_12");
  const poisoned = new URL("https://oginstagram.com/p/Ab_12?__gallery=1");
  const plainRoute = resolveContainerRoute(plain);
  const poisonedRoute = resolveContainerRoute(poisoned);
  assert.notEqual(plainRoute, null);
  assert.notEqual(poisonedRoute, null);
  assert.equal(poisonedRoute.rewritePath, "/p/Ab_12");
  assert.equal(poisonedRoute.cacheKey, plainRoute.cacheKey);

  const gallery = resolveContainerRoute(new URL("https://g.oginstagram.com/p/Ab_12?__gallery=0"));
  assert.notEqual(gallery, null);
  assert.equal(gallery.rewritePath, "/p/Ab_12?__gallery=1");
  assert.notEqual(gallery.cacheKey, plainRoute.cacheKey);
});

