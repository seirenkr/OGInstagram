test("case-insensitive story routes share one edge cache key", () => {
  for (const host of ["oginstagram.com", "g.oginstagram.com", "d.oginstagram.com"]) {
    const upperUrl = new URL(`https://${host}/stories/User.Name/123`);
    const lowerUrl = new URL(`https://${host}/stories/user.name/123`);
    const upper = resolveContainerRoute(upperUrl);
    const lower = resolveContainerRoute(lowerUrl);
    assert.notEqual(upper, null);
    assert.notEqual(lower, null);
    assert.equal(edgeCacheKey(upper, upperUrl), edgeCacheKey(lower, lowerUrl), host);
  }
  const direct = resolveContainerRoute(new URL("https://d.oginstagram.com/stories/User.Name/123"));
  assert.equal(direct.rewritePath, "/offload/story/user.name/123");
});

