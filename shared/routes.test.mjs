const offloadKey = Buffer.alloc(32);
const offloadKeyring = JSON.stringify({
  active: "test-v1",
  keys: { "test-v1": offloadKey.toString("base64url") },
});

function signOffload(path, expires, keyId = "test-v1", key = offloadKey) {
  return createHmac("sha256", key).update(signatureInput(keyId, path, expires)).digest("base64url");
}

