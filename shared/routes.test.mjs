test("offload capability matches the Go HMAC vector and shares one resource cache entry", async () => {
  assert.equal(
    signOffload("/offload/Ab_12/1", 4102444800),
    "CqgnG0rUpAoYVk7_SysTiO6WSXKBb4syu-WbZPuYDtY"
  );
  const expires = Math.floor(Date.now() / 1000) + 14 * 24 * 60 * 60 - 60;
  const signature = signOffload("/offload/Ab_12/1", expires);
  const raw = `https://oginstagram.com/offload/Ab_12/1?v=2&kid=test-v1&exp=${expires}&sig=${signature}`;
  const url = new URL(raw);
  const route = resolveContainerRoute(url);
  assert.notEqual(route, null);
  assert.equal(
    signatureInput("test-v1", route.offloadPath, 4102444800),
    "oginstagram-offload-capability\nv=2\nkid=test-v1\nexp=4102444800\npath=/offload/Ab_12/1\n"
  );
  assert.equal(await authorizeOffload(url, route.offloadPath, offloadKeyring), true);
  const rotated = JSON.stringify({
    active: "test-v2",
    keys: {
      "test-v1": "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA",
      "test-v2": Buffer.alloc(32, 1).toString("base64url"),
    },
  });
  assert.equal(await authorizeOffload(url, route.offloadPath, rotated), true);
  const signedKey = edgeCacheKey(route, url);
  assert.equal(signedKey, edgeCacheKey(route, new URL("https://oginstagram.com/offload/Ab_12/1")));

  // thumbnail and preview are representations of the same logical resource;
  // the dashboard adds them after receiving the signed media URL.
  const mutated = new URL(raw);
  mutated.searchParams.set("thumbnail", "1");
  mutated.searchParams.set("preview", "1");
  assert.equal(await authorizeOffload(mutated, route.offloadPath, offloadKeyring), true);
  const thumbnailRoute = resolveContainerRoute(mutated);
  assert.notEqual(edgeCacheKey(thumbnailRoute, mutated), signedKey);
});

test("offload capability rejects tampering, malformed input, and expiry abuse", async () => {
  const expires = Math.floor(Date.now() / 1000) + 60;
  const signature = signOffload("/offload/Ab_12/1", expires);
  const expired = Math.floor(Date.now() / 1000) - 60;
  const expiredSignature = signOffload("/offload/Ab_12/1", expired);
  const tooFar = Math.floor(Date.now() / 1000) + 14 * 24 * 60 * 60 + 60;
  const tooFarSignature = signOffload("/offload/Ab_12/1", tooFar);
  const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";
  const last = alphabet.indexOf(signature.at(-1));
  const nonCanonicalSignature = signature.slice(0, -1) + alphabet[last + 1];
  const signed = `v=2&kid=test-v1&exp=${expires}&sig=${signature}`;
  const cases = [
    `https://oginstagram.com/offload/Ab_12/2?${signed}`,
    `https://oginstagram.com/offload/ab_12/1?${signed}`,
    `https://oginstagram.com/offload/Ab_12/1?${signed}&sig=${signature}`,
    `https://oginstagram.com/offload/Ab_12/1?v=2&exp=${expires}&sig=${signature}`,
    `https://oginstagram.com/offload/Ab_12/1?v=2&kid=test-v1&sig=${signature}`,
    `https://oginstagram.com/offload/Ab_12/1?v=2&kid=missing&exp=${expires}&sig=${signature}`,
    `https://oginstagram.com/offload/Ab_12/1?v=1&kid=test-v1&exp=${expires}&sig=${signature}`,
    `https://oginstagram.com/offload/Ab_12/1?v=2&kid=test-v1&exp=${expires + 1}&sig=${signature}`,
    `https://oginstagram.com/offload/Ab_12/1?v=2&kid=test-v1&exp=0${expires}&sig=${signature}`,
    `https://oginstagram.com/offload/Ab_12/1?v=2&kid=test-v1&exp=${expired}&sig=${expiredSignature}`,
    `https://oginstagram.com/offload/Ab_12/1?v=2&kid=test-v1&exp=${tooFar}&sig=${tooFarSignature}`,
    `https://oginstagram.com/offload/Ab_12/1?v=2&kid=test-v1&exp=${expires}&sig=${nonCanonicalSignature}`,
    `https://oginstagram.com/offload/Ab_12/1?${signed}&thumbnail=0`,
    `https://oginstagram.com/offload/Ab_12/1?${signed}&preview=other`,
  ];
  for (const raw of cases) {
    const url = new URL(raw);
    const route = resolveContainerRoute(url);
    assert.notEqual(route, null, raw);
    assert.equal(await authorizeOffload(url, route.offloadPath, offloadKeyring), false, raw);
  }

  const partial = new URL("https://oginstagram.com/offload/Ab_12/1?sig=broken");
  const partialRoute = resolveContainerRoute(partial);
  assert.equal(await authorizeOffload(partial, partialRoute.offloadPath, offloadKeyring), false);

  const unsigned = new URL("https://oginstagram.com/offload/Ab_12/1");
  const unsignedRoute = resolveContainerRoute(unsigned);
  assert.equal(await authorizeOffload(unsigned, unsignedRoute.offloadPath, undefined), false);

  const valid = new URL(`https://oginstagram.com/offload/Ab_12/1?${signed}`);
  const validRoute = resolveContainerRoute(valid);
  await assert.rejects(
    authorizeOffload(valid, validRoute.offloadPath, JSON.stringify({
      active: "test-v1",
      keys: { "test-v1": "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA" },
      extra: true,
    })),
    /invalid keyring/
  );
  await assert.rejects(
    authorizeOffload(valid, validRoute.offloadPath, JSON.stringify({
      active: "test-v1",
      keys: { "test-v1": "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAB" },
    })),
    /base64url-encoded 32-byte/
  );
});

test("gateway strips client authorization headers and stamps only verified capability state", () => {
  const request = new Request("https://oginstagram.com/offload/Ab_12/1", {
    headers: {
      [internalHeader.allowOriginFetch]: "1",
      [internalHeader.signedOffload]: "1",
    },
  });
  const plain = stampGatewayHeaders(request, new URL(request.url), "request-1");
  assert.equal(plain.headers.get(internalHeader.allowOriginFetch), null);
  assert.equal(plain.headers.get(internalHeader.signedOffload), null);

  const signed = stampGatewayHeaders(request, new URL(request.url), "request-2", {
    signedOffload: true,
  });
  assert.equal(signed.headers.get(internalHeader.allowOriginFetch), null);
  assert.equal(signed.headers.get(internalHeader.signedOffload), "1");

  const httpUrl = new URL("http://www.oginstagram.com/p/Ab_12");
  const secure = stampGatewayHeaders(new Request(httpUrl), httpUrl, "request-3");
  assert.equal(secure.headers.get(internalHeader.publicOrigin), "https://www.oginstagram.com");
});

